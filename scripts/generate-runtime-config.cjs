#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

function readEnv(name, fallback = '') {
  const value = process.env[name];
  return typeof value === 'string' ? value.trim() : fallback;
}

function parseBoolean(value, fallback) {
  const normalized = String(value || '').trim().toLowerCase();
  if (!normalized) return fallback;
  if (['1', 'true', 'yes', 'on'].includes(normalized)) return true;
  if (['0', 'false', 'no', 'off'].includes(normalized)) return false;
  return fallback;
}

function escapeForJs(value) {
  return JSON.stringify(String(value));
}

function buildRuntimeConfig() {
  const backend = readEnv('TASKPOINTS_STORAGE_BACKEND', 'supabase') || 'supabase';
  const url = readEnv('TASKPOINTS_SUPABASE_URL') || readEnv('SUPABASE_URL') || 'http://127.0.0.1:54321';
  const anonKey =
    readEnv('TASKPOINTS_SUPABASE_ANON_KEY') ||
    readEnv('SUPABASE_ANON_KEY') ||
    'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6ImFub24iLCJleHAiOjE5ODM4MTI5OTZ9.CRXP1A7WOeoJeXxjNni43kdQwgnWNReilDMblYTn_I0';
  const schema = readEnv('TASKPOINTS_SUPABASE_SCHEMA', 'public') || 'public';
  const taskTimerEnabled = parseBoolean(readEnv('TASKPOINTS_ENABLE_TASK_TIMER'), false);

  return `/* global window */
// Generated by scripts/generate-runtime-config.cjs.
window.__TASKPOINTS_DB__ = {
  backend: ${escapeForJs(backend)},
  url: ${escapeForJs(url)},
  anonKey: ${escapeForJs(anonKey)},
  schema: ${escapeForJs(schema)},
};

window.__TASKPOINTS_FLAGS__ = {
  task_timer_enabled: ${taskTimerEnabled},
};
`;
}

function main() {
  const targetPath = path.resolve(process.cwd(), 'config.js');
  const contents = buildRuntimeConfig();
  fs.writeFileSync(targetPath, contents, 'utf8');
  console.log(`Runtime config generated at ${targetPath}`);
}

if (require.main === module) {
  main();
}
